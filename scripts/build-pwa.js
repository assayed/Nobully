// Turns the Expo web export (dist/) into two test builds:
//   dist-pwa/       installable PWA for any HTTPS host: manifest, icons, offline service worker
//   dist-artifact/  the same game for a Claude Artifact link (no service worker there;
//                   every file path is resolved from the page's own folder at runtime)
// Run: npm run build:pwa   (runs `expo export -p web` first)
const fs = require('fs');
const path = require('path');
const crypto = require('crypto');

const root = path.join(__dirname, '..');
const dist = path.join(root, 'dist');
const pkg = require(path.join(root, 'package.json'));

const THEME = '#FF7A00';
const BG = '#FFF7E8';

function copyDir(from, to) {
  fs.rmSync(to, { recursive: true, force: true });
  fs.cpSync(from, to, { recursive: true });
}
function walk(dir, base = dir) {
  return fs.readdirSync(dir, { withFileTypes: true }).flatMap((e) => {
    const p = path.join(dir, e.name);
    return e.isDirectory() ? walk(p, base) : [path.relative(base, p).split(path.sep).join('/')];
  });
}
const scriptsOf = (html) => [...html.matchAll(/<script src="([^"]+)"[^>]*><\/script>/g)].map((m) => m[1]);

if (!fs.existsSync(path.join(dist, 'index.html'))) {
  console.error('dist/index.html missing: run `npx expo export -p web` first');
  process.exit(1);
}
const html = fs.readFileSync(path.join(dist, 'index.html'), 'utf8');
const entryScripts = scriptsOf(html);
const resetCss = html.match(/<style id="expo-reset">([\s\S]*?)<\/style>/)[1];

// ---------- 1. dist-pwa ----------
const pwa = path.join(root, 'dist-pwa');
copyDir(dist, pwa);
for (const [src, dst] of [['pwa-192.png', 'icon-192.png'], ['pwa-512.png', 'icon-512.png'], ['pwa-maskable-512.png', 'icon-maskable-512.png'], ['apple-touch-icon.png', 'apple-touch-icon.png']]) {
  fs.copyFileSync(path.join(root, 'assets', src), path.join(pwa, dst));
}
fs.writeFileSync(path.join(pwa, 'manifest.webmanifest'), JSON.stringify({
  name: 'HeroKid – هيروكيد',
  short_name: 'HeroKid',
  description: 'لعبة للأطفال عن الأخلاق الحلوة ووقف التنمر · A kids\' game about kindness and standing up to bullying',
  lang: 'ar',
  dir: 'rtl',
  start_url: './',
  scope: './',
  display: 'standalone',
  orientation: 'portrait',
  background_color: BG,
  theme_color: THEME,
  icons: [
    { src: 'icon-192.png', sizes: '192x192', type: 'image/png' },
    { src: 'icon-512.png', sizes: '512x512', type: 'image/png' },
    { src: 'icon-maskable-512.png', sizes: '512x512', type: 'image/png', purpose: 'maskable' },
  ],
}, null, 2));

const pwaHead = `    <meta name="theme-color" content="${THEME}" />
    <meta name="mobile-web-app-capable" content="yes" />
    <meta name="apple-mobile-web-app-capable" content="yes" />
    <meta name="apple-mobile-web-app-title" content="HeroKid" />
    <link rel="manifest" href="./manifest.webmanifest" />
    <link rel="apple-touch-icon" href="./apple-touch-icon.png" />`;
const pwaRegister = `<script>
  if ('serviceWorker' in navigator) {
    window.addEventListener('load', function () { navigator.serviceWorker.register('./sw.js').catch(function () {}); });
  }
</script>`;
let pwaHtml = html
  .replace('<html lang="en">', '<html lang="ar" dir="rtl">')
  .replace('<meta name="viewport" content="width=device-width, initial-scale=1, shrink-to-fit=no" />',
    '<meta name="viewport" content="width=device-width, initial-scale=1, viewport-fit=cover" />' + pwaHead)
  .replace(`<style id="expo-reset">`, `<style>body{background:${BG}}</style>\n    <style id="expo-reset">`)
  .replace('</body>', pwaRegister + '\n</body>');
fs.writeFileSync(path.join(pwa, 'index.html'), pwaHtml);

// Service worker: precache every file; the cache name changes when any file changes.
const files = walk(pwa).filter((f) => f !== 'sw.js' && f !== 'metadata.json');
const hash = crypto.createHash('sha256');
for (const f of files.sort()) hash.update(f).update(fs.readFileSync(path.join(pwa, f)));
const version = `${pkg.version}-${hash.digest('hex').slice(0, 10)}`;
fs.writeFileSync(path.join(pwa, 'sw.js'), `// HeroKid offline cache (generated by scripts/build-pwa.js)
const CACHE = 'herokid-${version}';
const FILES = ${JSON.stringify(['./', ...files.map((f) => './' + encodeURI(f))], null, 0)};

self.addEventListener('install', (e) => {
  e.waitUntil(caches.open(CACHE).then((c) => c.addAll(FILES)).then(() => self.skipWaiting()));
});
self.addEventListener('activate', (e) => {
  e.waitUntil(caches.keys()
    .then((keys) => Promise.all(keys.filter((k) => k.startsWith('herokid-') && k !== CACHE).map((k) => caches.delete(k))))
    .then(() => self.clients.claim()));
});
self.addEventListener('fetch', (e) => {
  const req = e.request;
  if (req.method !== 'GET' || new URL(req.url).origin !== location.origin) return;
  // Screens are client-side routes: any page navigation gets the app shell.
  if (req.mode === 'navigate') {
    e.respondWith(fetch(req).catch(() => caches.match('./index.html', { ignoreSearch: true }).then((r) => r || caches.match('./'))));
    return;
  }
  e.respondWith(caches.match(req, { ignoreSearch: true }).then((hit) => hit || fetch(req).then((res) => {
    if (res.ok) { const copy = res.clone(); caches.open(CACHE).then((c) => c.put(req, copy)); }
    return res;
  })));
});
`);
// Screens use absolute paths (/home, /world/…), so host dist-pwa at the root of a (sub)domain.

// ---------- 2. dist-artifact ----------
const art = path.join(root, 'dist-artifact');
copyDir(dist, art);
fs.rmSync(path.join(art, 'index.html'));
fs.rmSync(path.join(art, 'metadata.json'), { force: true });
// The artifact service reserves names starting with "_": move the bundles to js/ with plain names.
const renames = {};
fs.mkdirSync(path.join(art, 'js'));
for (const f of fs.readdirSync(path.join(art, '_expo/static/js/web'))) {
  const to = f.replace(/^_+/, '').replace(/[^A-Za-z0-9.-]/g, '');
  renames[f] = to;
  fs.renameSync(path.join(art, '_expo/static/js/web', f), path.join(art, 'js', to));
}
fs.rmSync(path.join(art, '_expo'), { recursive: true });
fixPaths(art, renames);
const boot = `<script>
  // Files live next to this page; remember that folder, then show the title screen.
  window.__HK_BASE = location.href.replace(/[?#].*$/, '').replace(/[^/]*$/, '');
  try { history.replaceState(null, '', '/' + location.hash); } catch (e) {}
  ${JSON.stringify(entryScripts.map((s) => 'js/' + renames[path.basename(s)]))}.forEach(function (s) {
    var el = document.createElement('script'); el.src = window.__HK_BASE + s; el.async = false; document.body.appendChild(el);
  });
</script>`;
fs.writeFileSync(path.join(art, 'index.html'), `<title>HeroKid</title>
<style id="expo-reset">${resetCss}
  body { background: ${BG}; }
</style>
<div id="root"></div>
${boot}
`);

console.log(`dist-pwa (cache ${version}): ${files.length} files`);
console.log(`dist-artifact: ${walk(art).length} files`);

/** Rewrites absolute "/_expo" and "/assets" paths inside the JS bundles. */
function fixPaths(dir, renames) {
  const jsDir = path.join(dir, 'js');
  for (const f of fs.readdirSync(jsDir)) {
    const p = path.join(jsDir, f);
    let s = fs.readFileSync(p, 'utf8')
      .replace(/"\/_expo\/static\/js\/web\/([^"]+)"/g, (_, name) => `(window.__HK_BASE||"/")+"js/${renames[name] || name}"`)
      .replace(/"\/assets\//g, '(window.__HK_BASE||"/")+"assets/');
    fs.writeFileSync(p, s);
  }
}
